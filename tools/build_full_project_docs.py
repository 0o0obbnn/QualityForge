def load_openapi():
    ruby = "require 'yaml'; require 'json'; puts JSON.generate(YAML.load_file(ARGV[0]))"
    result = subprocess.run(["ruby", "-e", ruby, str(API_YAML)], check=True, capture_output=True, text=True)
