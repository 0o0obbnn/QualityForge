def schema_label(schema):
    if not schema:
        return "无"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "allOf" in schema:
        return " + ".join(schema_label(x) for x in schema["allOf"])
    if "oneOf" in schema:
        return "oneOf(" + ", ".join(schema_label(x) for x in schema["oneOf"]) + ")"
    if "anyOf" in schema:
        return "anyOf(" + ", ".join(schema_label(x) for x in schema["anyOf"]) + ")"
    typ = schema.get("type", "object")
    if typ == "array":
        return f"array<{schema_label(schema.get('items', {}))}>"
    if "enum" in schema:
        return typ + "{" + ", ".join(map(str, schema["enum"])) + "}"
    return typ + (("/" + schema["format"]) if schema.get("format") else "")


def request_label(op):
    rb = op.get("requestBody") or {}
    content = rb.get("content") or {}
    parts = []
    for media, body in content.items():
        parts.append(f"{media}: {schema_label(body.get('schema') or {})}")
    return "\n".join(parts) if parts else "无请求体"


def params_label(path_item, op):
    params = list(path_item.get("parameters") or []) + list(op.get("parameters") or [])
    if not params:
        return "无"
    out = []
    for p in params:
        if "$ref" in p:
            out.append(p["$ref"].split("/")[-1])
            continue
        req = "必填" if p.get("required") else "可选"
        out.append(f"{p.get('in', '?')} {p.get('name', '?')} ({req}, {schema_label(p.get('schema') or {})})")
    return "；".join(out)


def response_label(op):
    out = []
    for code, resp in (op.get("responses") or {}).items():
        content = (resp or {}).get("content") or {}
        schemas = [schema_label(x.get("schema") or {}) for x in content.values()]
        desc = (resp or {}).get("description", "")
        shape = "/".join(dict.fromkeys(schemas)) if schemas else "无响应体"
        out.append(f"{code} {shape}{(' - ' + desc) if desc else ''}")
    return "；".join(out) if out else "未定义"


def security_label(global_security, op):
    sec = op.get("security", global_security)
    if sec == []:
        return "匿名"
    names = []
    for item in sec or []:
        names.extend(item.keys())
    return " / ".join(dict.fromkeys(names)) if names else "未声明"


