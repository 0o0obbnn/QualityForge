def add_small_label(doc, text, color=MUTED):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(text)
    set_font(r, 9, bold=True, color=color)
    return p


def add_acceptance(doc, req_id, given, when, then):
    add_small_label(doc, req_id, INK)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(7)
    for label, text in (("Given ", given), ("When ", when), ("Then ", then)):
        r = p.add_run(label)
        set_font(r, 10, bold=True, color=INK)
        r2 = p.add_run(text + ("；" if label != "Then " else "。"))
        set_font(r2, 10)


